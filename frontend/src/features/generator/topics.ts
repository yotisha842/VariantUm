/** Возвращает список тем для заданного предмета и класса. */
export function getTopics(subject: string | null, grade: number | null): string[] {
  if (!subject || !grade) return [];
  const sv = SUBJECT_VALUES[subject];
  if (!sv || sv === 'other') return [];
  const gg = gradeGroup(grade);
  if (!gg) return [];
  return TOPIC_DB[sv]?.[gg] ?? [];
}
